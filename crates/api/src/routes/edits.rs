//! Applying edits, fetching the generated result, and accepting it as a new image.

use axum::Json;
use axum::extract::State;
use axum::http::{StatusCode, header};
use axum::response::{IntoResponse, Response};
use hands_off_core::model::{EditRequest, ImageRecord};
use hands_off_core::storage::BlobKey;
use hands_off_core::{Error, ImageId, JobId};

use crate::edit;
use crate::error::{ApiError, ApiJson, ApiPath, ErrorBody};
use crate::ingest::{Origin, ingest_version};
use crate::routes::images::JobCreated;
use crate::state::AppState;

/// Apply a batch of edits to an image.
///
/// Starts a job that summarises the edits, asks the image model for the result using the
/// preview as a geometry reference, and blends it into the original so only the edited areas
/// change. Follow it with the job's event stream, then fetch the result.
#[utoipa::path(
    post,
    path = "/api/v1/images/{id}/edits",
    tag = "edits",
    params(("id" = ImageId, Path, description = "Image id")),
    request_body = EditRequest,
    responses(
        (status = 202, description = "Edit started", body = JobCreated),
        (status = 400, description = "Malformed edits", body = ErrorBody),
        (status = 404, description = "Unknown or unanalysed image", body = ErrorBody),
        (status = 413, description = "Preview too large", body = ErrorBody),
    )
)]
pub async fn apply_edits(
    State(state): State<AppState>,
    ApiPath(id): ApiPath<ImageId>,
    ApiJson(request): ApiJson<EditRequest>,
) -> Result<(StatusCode, Json<JobCreated>), ApiError> {
    state
        .store
        .image_by_id(id)
        .await?
        .ok_or(Error::NotFound("image"))?;
    let prepared = edit::prepare(&state, id, request).await?;
    let worker = state.clone();
    let job_id = state
        .jobs
        .spawn("edit", move |context| async move {
            edit::execute(&worker, prepared, &context).await
        })
        .await?;
    Ok((StatusCode::ACCEPTED, Json(JobCreated { job_id })))
}

/// Download the image generated by a finished edit job (PNG).
#[utoipa::path(
    get,
    path = "/api/v1/jobs/{id}/result",
    tag = "edits",
    params(("id" = JobId, Path, description = "Job id")),
    responses(
        (status = 200, description = "The edited image", content_type = "image/png", body = Vec<u8>),
        (status = 404, description = "No result for this job", body = ErrorBody),
    )
)]
pub async fn get_result(
    State(state): State<AppState>,
    ApiPath(id): ApiPath<JobId>,
) -> Result<Response, ApiError> {
    edit::stored_result(&state, id).await?;
    let bytes = state.blobs.get(&BlobKey::job_result(id)).await?;
    Ok((
        [
            (header::CONTENT_TYPE, "image/png"),
            (header::CACHE_CONTROL, "private, max-age=3600"),
        ],
        bytes,
    )
        .into_response())
}

/// Accept an edit: store its result as a new image that can be edited further.
#[utoipa::path(
    post,
    path = "/api/v1/jobs/{id}/accept",
    tag = "edits",
    params(("id" = JobId, Path, description = "Job id")),
    responses(
        (status = 201, description = "The accepted result as a new image", body = ImageRecord),
        (status = 200, description = "An identical image already existed", body = ImageRecord),
        (status = 404, description = "No result for this job", body = ErrorBody),
    )
)]
pub async fn accept(
    State(state): State<AppState>,
    ApiPath(id): ApiPath<JobId>,
) -> Result<(StatusCode, Json<ImageRecord>), ApiError> {
    let stored = edit::stored_result(&state, id).await?;
    let parent = state
        .store
        .image_by_id(stored.image_id)
        .await?
        .ok_or(Error::NotFound("image"))?;
    let bytes = state.blobs.get(&BlobKey::job_result(id)).await?;
    let origin = Origin {
        parent,
        edit: stored.result,
    };
    let (record, created) = ingest_version(&state, bytes, Some(origin)).await?;
    let status = if created {
        StatusCode::CREATED
    } else {
        StatusCode::OK
    };
    Ok((status, Json(record)))
}

/// Throw away the result of an edit that was not accepted.
#[utoipa::path(
    delete,
    path = "/api/v1/jobs/{id}/result",
    tag = "edits",
    params(("id" = JobId, Path, description = "Job id")),
    responses(
        (status = 204, description = "Result removed"),
        (status = 404, description = "No result for this job", body = ErrorBody),
    )
)]
pub async fn discard(
    State(state): State<AppState>,
    ApiPath(id): ApiPath<JobId>,
) -> Result<StatusCode, ApiError> {
    edit::stored_result(&state, id).await?;
    state.blobs.remove_tree(&BlobKey::job_dir(id)).await?;
    Ok(StatusCode::NO_CONTENT)
}
