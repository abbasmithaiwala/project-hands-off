#[tokio::test]
async fn malformed_edits_fail_immediately_with_a_clear_message_and_cost_nothing() {
    let app = edit_app().await;
    let id = analysed(&app).await;
    let edit = |change: Value, object: u32, property: &str| json!({ "object_id": object, "property": property, "change": change });
    let slider = |value: f64| json!({ "kind": "slider", "value": value });
    let point = json!({ "x": 0.5, "y": 0.5 });

    let cases: Vec<(&str, Value, &str)> = vec![
        ("no edits", json!({ "edits": [] }), "at least one edit"),
        (
            "unknown object",
            json!({ "edits": [edit(slider(0.5), 9, "length")] }),
            "unknown object",
        ),
        (
            "duplicate property",
            json!({ "edits": [edit(slider(0.5), 0, "length"), edit(slider(0.6), 0, "length")] }),
            "repeats",
        ),
        (
            "zero slider",
            json!({ "edits": [edit(slider(0.0), 0, "length")] }),
            "slider value",
        ),
        (
            "huge slider",
            json!({ "edits": [edit(slider(9.0), 0, "length")] }),
            "slider value",
        ),
        (
            "mismatched points",
            json!({ "edits": [edit(json!({ "kind": "multi_handle", "origin": [point, point], "target": [point] }), 0, "arms")] }),
            "same number of points",
        ),
        (
            "out-of-range point",
            json!({ "edits": [edit(json!({ "kind": "multi_handle", "origin": [{ "x": 3.0, "y": 0.5 }], "target": [point] }), 0, "arms")] }),
            "",
        ),
        (
            "bad preview",
            json!({ "edits": [edit(slider(0.5), 0, "length")], "preview_png": "!!!" }),
            "base64",
        ),
        (
            "preview that is not an image",
            json!({ "edits": [edit(slider(0.5), 0, "length")], "preview_png": base64_encode(b"not an image") }),
            "",
        ),
        (
            "bad model id",
            json!({ "edits": [edit(slider(0.5), 0, "length")], "model": "no spaces!" }),
            "model id",
        ),
    ];
    for (name, body, expected) in cases {
        let (status, message) = rejected(&app, &id, body).await;
        assert!(status.is_client_error(), "{name}: {status}");
        assert!(message.contains(expected), "{name}: {message}");
    }
    assert!(
        app.generator.requests().is_empty(),
        "invalid requests never reach the image model"
    );
    assert!(app.llm.requests().is_empty());
}

