#[tokio::test]
async fn accepting_a_result_creates_a_new_image_once() {
    let app = edit_app().await;
    app.llm.push_ok(SUMMARY_JSON);
    app.generator
        .push_image(solid_png(WIDTH, HEIGHT, [250, 250, 250]));
    let id = analysed(&app).await;
    let (_, json, _) = run_edit(&app.app, &id, &slider_edit_body(None)).await;
    let path = format!("/api/v1/jobs/{}/accept", job_id(&json));

    let first = send(&app.app, Request::post(&path).body(Body::empty()).unwrap()).await;
    assert_eq!(first.status, StatusCode::CREATED);
    let record = first.json();
    assert_ne!(record["id"].as_str().unwrap(), id);
    assert_eq!(
        (record["width"].as_u64(), record["height"].as_u64()),
        (Some(120), Some(80))
    );

    let bytes = get(
        &app.app,
        &format!("/api/v1/images/{}/original", record["id"].as_str().unwrap()),
    )
    .await
    .body;
    let result = get(&app.app, &format!("/api/v1/jobs/{}/result", job_id(&json)))
        .await
        .body;
    assert_eq!(
        bytes, result,
        "the new image is exactly the reviewed result"
    );

    let again = send(&app.app, Request::post(&path).body(Body::empty()).unwrap()).await;
    assert_eq!(again.status, StatusCode::OK);
    assert_eq!(again.json()["id"], record["id"]);
}

