#[tokio::test]
async fn cancelling_stops_the_job_promptly_even_mid_generation() {
    let app = edit_app().await;
    app.llm.push_ok(SUMMARY_JSON);
    app.generator.set_delay(Duration::from_secs(60));
    app.generator
        .push_image(solid_png(WIDTH, HEIGHT, [1, 2, 3]));
    let id = analysed(&app).await;

    let response = post_json(
        &app.app,
        &format!("/api/v1/images/{id}/edits"),
        &slider_edit_body(None),
    )
    .await;
    let job = job_id(&response.json());
    while app.generator.requests().is_empty() {
        tokio::time::sleep(Duration::from_millis(20)).await;
    }

    let started = Instant::now();
    let cancel = send(
        &app.app,
        Request::delete(format!("/api/v1/jobs/{job}"))
            .body(Body::empty())
            .unwrap(),
    )
    .await;
    assert_eq!(cancel.status, StatusCode::ACCEPTED);
    let events: Vec<JobEvent> = futures::StreamExt::collect(
        app.app
            .state
            .jobs
            .events(job.parse().unwrap())
            .await
            .unwrap(),
    )
    .await;

    assert_eq!(events.last(), Some(&JobEvent::Cancelled));
    assert!(
        started.elapsed() < Duration::from_secs(5),
        "cancellation must not wait for the model"
    );
    assert_eq!(
        get(&app.app, &format!("/api/v1/jobs/{job}/result"))
            .await
            .status,
        StatusCode::NOT_FOUND
    );
}

