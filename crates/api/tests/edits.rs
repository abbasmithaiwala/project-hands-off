const WIDTH: u32 = 120;
const HEIGHT: u32 = 80;

async fn analysed(app: &EditApp) -> String {
    analysed_image(&app.app).await
}

fn completed_result(events: &[JobEvent]) -> Value {
    match events.last() {
        Some(JobEvent::Completed {
            result: Some(result),
        }) => result.clone(),
        other => panic!("expected a completed job with a result, got {other:?}"),
    }
}

fn failure(events: &[JobEvent]) -> (ErrorCode, String) {
    match events.last() {
        Some(JobEvent::Failed { code, message }) => (*code, message.clone()),
        other => panic!("expected a failed job, got {other:?}"),
    }
}

fn job_id(json: &Value) -> String {
    json["job_id"].as_str().unwrap().to_owned()
}

#[tokio::test]
async fn an_edit_runs_through_every_stage_and_produces_a_result() {
    let app = edit_app().await;
    app.llm.push_ok(SUMMARY_JSON);
    app.generator
        .push_image(solid_png(WIDTH, HEIGHT, [250, 250, 250]));
    let id = analysed(&app).await;

    let (status, _, events) = run_edit(
        &app.app,
        &id,
        &slider_edit_body(Some(&solid_png(WIDTH, HEIGHT, [9, 9, 9]))),
    )
    .await;

    assert_eq!(status, StatusCode::ACCEPTED);
    assert_eq!(
        stages(&events),
        ["analysing", "planning", "generating", "compositing", "done"]
    );
    let result = completed_result(&events);
    assert_eq!(result["summary"], "Shortened the couch");
    assert_eq!(
        result["changes"][0]["text"],
        "Shortened the couch to about 60% of its length"
    );
    assert_eq!(result["model"], "google/gemini-3-pro-image");
    assert_eq!(result["cost_usd"], 0.05);
    assert!(
        result["instruction"]
            .as_str()
            .unwrap()
            .contains("40% shorter")
    );

    let logs: Vec<&str> = events
        .iter()
        .filter_map(|e| match e {
            JobEvent::Log { line } => Some(line.as_str()),
            _ => None,
        })
        .collect();
    assert!(
        logs.iter()
            .any(|l| l.starts_with("Instruction: Make the couch")),
        "{logs:?}"
    );
    assert!(
        logs.iter().any(
            |l| l.contains("Generated by google/gemini-3-pro-image in") && l.contains("$0.050")
        ),
        "{logs:?}"
    );
}

#[tokio::test]
async fn only_the_edited_region_of_the_original_changes() {
    let app = edit_app().await;
    app.llm.push_ok(SUMMARY_JSON);
    let id = analysed(&app).await;
    let original = image::load_from_memory(
        &get(&app.app, &format!("/api/v1/images/{id}/original"))
            .await
            .body,
    )
    .unwrap()
    .to_rgb8();
    // The model returns the same picture with a bright patch where the couch is. The rest matches,
    // so colour correction has nothing to fix.
    let mut generated = original.clone();
    for y in 25..55 {
        for x in 40..80 {
            generated.put_pixel(x, y, image::Rgb([250, 250, 250]));
        }
    }
    let mut encoded = std::io::Cursor::new(Vec::new());
    generated
        .write_to(&mut encoded, image::ImageFormat::Png)
        .unwrap();
    app.generator.push_image(encoded.into_inner());

    let (_, json, events) = run_edit(&app.app, &id, &slider_edit_body(None)).await;
    completed_result(&events);
    let result_response = get(&app.app, &format!("/api/v1/jobs/{}/result", job_id(&json))).await;
    assert_eq!(result_response.status, StatusCode::OK);
    assert_eq!(result_response.headers["content-type"], "image/png");
    let result = image::load_from_memory(&result_response.body)
        .unwrap()
        .to_rgb8();

    assert_eq!(
        result.dimensions(),
        (WIDTH, HEIGHT),
        "the result keeps the original resolution"
    );
    for (x, y, pixel) in original.enumerate_pixels() {
        let outside = !(24..96).contains(&x) || !(16..64).contains(&y);
        if outside {
            assert_eq!(
                result.get_pixel(x, y),
                pixel,
                "({x}, {y}) changed outside the edited region"
            );
        }
    }
    let centre = result.get_pixel(WIDTH / 2, HEIGHT / 2);
    assert!(
        centre[0] > 200,
        "the centre should come from the generated image, got {centre:?}"
    );
}

