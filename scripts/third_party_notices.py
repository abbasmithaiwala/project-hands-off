#!/usr/bin/env python3
"""Write (or check) THIRD_PARTY_NOTICES.md from the dependency graph.

Rust: every crate linked into the server (`cargo tree`), with its declared licence.
Web: every production npm package in web/package-lock.json, with its declared licence.
Plus the things that are not packages: the ONNX Runtime, the detection model and the sample photo.

    python3 scripts/third_party_notices.py          # rewrite the file
    python3 scripts/third_party_notices.py --check  # fail if the file is out of date
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"

NOT_PACKAGES = [
    (
        "ONNX Runtime",
        "MIT",
        "https://github.com/microsoft/onnxruntime",
        "Runs the detection model; linked into the server binary by the `ort` crate.",
    ),
    (
        "RF-DETR-Seg (Medium) weights",
        "Apache-2.0",
        "https://github.com/roboflow/rf-detr",
        "Downloaded on first run (never bundled in the repository or the image). Only Apache-2.0 sizes are used.",
    ),
    (
        "Sample photo \"ORANGE SOFA.jpg\" by BORNTHISWAYMEDIA",
        "CC BY-SA 4.0",
        "https://commons.wikimedia.org/wiki/File:ORANGE_SOFA.jpg",
        "Offered on the landing page as a try-it photo (`web/public/sample/`). Licence: https://creativecommons.org/licenses/by-sa/4.0",
    ),
]


def rust_packages():
    out = subprocess.run(
        ["cargo", "tree", "-p", "hands-off-api", "--edges", "normal,build", "--prefix", "none",
         "--format", "{p}|{l}|{r}", "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    found = {}
    for line in out.splitlines():
        parts = line.split("|")
        if len(parts) != 3 or "(/" in parts[0] and "hands-off" in parts[0]:
            continue
        match = re.match(r"([^\s]+) v([^\s]+)", parts[0])
        if not match:
            continue
        name, version = match.groups()
        found[(name, version)] = (parts[1].strip() or "UNKNOWN", parts[2].strip())
    return [(n, v, lic, repo) for (n, v), (lic, repo) in sorted(found.items())]


def npm_packages():
    lock = json.loads((ROOT / "web/package-lock.json").read_text())
    found = {}
    for path, info in lock["packages"].items():
        if not path or info.get("dev") or info.get("optional"):
            continue
        name = path.split("node_modules/")[-1]
        found[(name, info.get("version", "?"))] = info.get("license", "UNKNOWN")
    return [(n, v, lic) for (n, v), lic in sorted(found.items())]


def render():
    rust, npm = rust_packages(), npm_packages()
    lines = [
        "# Third-party notices",
        "",
        "Hands-Off is licensed under the MIT License (see `LICENSE`). It includes and depends on the",
        "software below, each under its own licence. This file is generated by",
        "`scripts/third_party_notices.py`; do not edit it by hand.",
        "",
        "Model weights, the ONNX Runtime and the sample photo are listed first because they are not packages.",
        "No model weights are stored in this repository or in the container image: they are downloaded on first run.",
        "",
        "## Not packages",
        "",
        "| Component | Licence | Source | Notes |",
        "|---|---|---|---|",
    ]
    lines += [f"| {n} | {lic} | <{src}> | {note} |" for n, lic, src, note in NOT_PACKAGES]
    lines += ["", f"## Rust crates ({len(rust)})", "", "| Crate | Version | Licence | Source |", "|---|---|---|---|"]
    lines += [f"| {n} | {v} | {lic} | {('<' + r + '>') if r else ''} |" for n, v, lic, r in rust]
    lines += ["", f"## npm packages, production ({len(npm)})", "", "| Package | Version | Licence |", "|---|---|---|"]
    lines += [f"| {n} | {v} | {lic} |" for n, v, lic in npm]
    lines += [
        "",
        "Full licence texts are in each package's source distribution, linked above or on crates.io and npmjs.com.",
        "",
    ]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("THIRD_PARTY_NOTICES.md is out of date: run `just notices`")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
